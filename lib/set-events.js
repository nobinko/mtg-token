import { mkdir, readFile, writeFile } from "./storage.js";
import { dirname, resolve } from "node:path";
import { fetchJson } from "./cache.js";
import { scryfallCacheTtlMs } from "./config.js";
import { modernAdditionalSetCodes, supplementalSetForFormat } from "./modern-sets.js";
import { constructedSetLegality } from "./set-legality.js";

// セット発売の環境イベントを Scryfall /sets から自動生成する。
// これにより data/environment-events.json に手書きするのは
// 禁止改定とローテーションだけになる（定期メンテの主要な事故源だった）。
const setsCachePath = resolve(".cache", "scryfall", "sets.json");
export const setEventVersion = 3;

const SET_EVENT_FORMATS = ["standard", "pioneer", "modern", "legacy"];
const FORMAT_LABELS = { standard: "Standard", pioneer: "Pioneer", modern: "Modern", legacy: "Legacy" };

function setEventFormats(set) {
  if (set.digital || !set.released_at) return [];
  if (!modernAdditionalSetCodes.includes(set.code) && ["expansion", "core"].includes(set.set_type)) return SET_EVENT_FORMATS;
  return SET_EVENT_FORMATS.filter((format) => supplementalSetForFormat(set, format));
}

function toSetEvent(set) {
  const formats = setEventFormats(set);
  const groups = new Map();
  for (const format of formats) {
    const legality = constructedSetLegality(set.code, format);
    const date = legality?.date || set.released_at;
    if (!groups.has(date)) groups.set(date, { formats: [], legality });
    groups.get(date).formats.push(format);
  }
  return [...groups].map(([date, { formats, legality }]) => ({
    setCode: set.code,
    date,
    type: "set-release",
    title: `${set.name} tabletop release`,
    sourceUrl: legality?.sourceUrl || set.scryfall_uri || "https://scryfall.com/sets",
    formatsAffected: [...formats],
    changes: Object.fromEntries(
      formats.map((format) => [format, legality ? `${set.name}: ${FORMAT_LABELS[format]}の構築適用日は${date}です。販売開始日とは区別しています。` : `${set.name}: ${FORMAT_LABELS[format]}の構築適用日は未確認です。発売日を暫定起点としています。`])
    ),
    autoGenerated: true,
    ...(legality ? { confirmed: true, effectiveDate: date } : {})
  }));
}

async function readSetsCache({ allowStale = false } = {}) {
  try {
    const raw = await readFile(setsCachePath, "utf8");
    const entry = JSON.parse(raw);
    if (!Array.isArray(entry?.sets)) return null;
    if (!allowStale && Date.now() > Number(entry.expiresAt || 0)) return null;
    return entry.sets;
  } catch {
    return null;
  }
}

async function writeSetsCache(sets) {
  await mkdir(dirname(setsCachePath), { recursive: true });
  await writeFile(setsCachePath, JSON.stringify({
    fetchedAt: new Date().toISOString(),
    expiresAt: Date.now() + scryfallCacheTtlMs,
    sets
  }), "utf8");
}

export function setReleaseEventsFromSets(sets) {
  return (sets || []).filter((set) => setEventFormats(set).length).flatMap(toSetEvent);
}

export async function fetchSetCatalog({ refresh = false, persist = true } = {}) {
  const cached = await readSetsCache();
  if (cached && !refresh) return { sets: cached, source: "cache", warning: "" };

  try {
    let url = "https://api.scryfall.com/sets";
    const sets = [];
    while (url) {
      const data = await fetchJson(url);
      sets.push(...(data.data || []));
      url = data.has_more ? data.next_page : null;
    }
    if (!sets.length) throw new Error("セット情報が空です。");
    if (persist) await writeSetsCache(sets);
    return { sets, source: "live", warning: "" };
  } catch (error) {
    if (refresh) throw error;
    // オフラインや Scryfall 障害では検索自体を止めず、期限切れキャッシュ→手書きイベントのみ、と段階的に縮退する
    const stale = await readSetsCache({ allowStale: true });
    if (stale) {
      console.log(`[sets] using stale set list: ${error.message}`);
      return { sets: stale, source: "stale", warning: "セット一覧の再取得に失敗したため、保存済みの一覧です。最新の予定は未確認です。" };
    }
    console.log(`[sets] set list unavailable (${error.message}); manual events only`);
    return { sets: [], source: "bundled", warning: "セット一覧を取得できないため、本体の環境履歴にある候補だけを表示しています。" };
  }
}

export async function fetchSetReleaseEvents(options = {}) {
  return setReleaseEventsFromSets((await fetchSetCatalog(options)).sets);
}
